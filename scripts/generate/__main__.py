"""Live-card generator: python -m scripts.generate --out DIR [--fixtures DIR] [--now ISO].

Run by the profile Action every 3 hours; its output is force-pushed to the
`output` branch as DIR/{jp,en}/<name>.svg.

Order of defences (spec §7.3):
  1. no activity card renders a repo name (owner edit 3): the this-week card and
     the plaques read only the anonymous contribution calendar, so Data.events and
     Data.recent_repos never reach a card;
  2. every rendered SVG then goes through privacy.check;
  3. output is written to a temp dir next to DIR and swapped in only when all of
     the above succeeded. On any failure DIR is left untouched and we exit 1.

--out guard: DIR must be missing, empty, or an earlier output (it carries the
`.shrine-output` marker), so a mistyped --out can never wipe someone's files.

Logging: counts, file names, exception types and masked messages only. Never a
token, a deny-list term or a private repo name. Stdlib only.
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from scripts.generate.github_data import Data, fetch, load_fixture
from scripts.generate.privacy import check, parse_denylist, scrub
from scripts.shrine import content
from scripts.shrine.cards.live import render_enso, render_hours, render_stat, render_torii_path, render_week
from scripts.shrine.cards.plaque import render_plaque
from scripts.shrine.fonts import RuntimeFonts

ROOT = Path(__file__).resolve().parent.parent.parent
KITSUNE = ROOT / "assets" / "common" / "kitsune-sheet.png"
LOGIN = "sky9262"
LANGS = ("jp", "en")
LAYOUTS = ("desktop", "phone")
STATS = ("contrib", "month", "peak", "stars")
LIVE_PLAQUE = "phisheye"
MARKER = ".shrine-output"  # marks a dir as ours, so --out never replaces anything else
MARKER_TEXT = "Generated by python -m scripts.generate; replaced on every run.\n"


def parse_now(s: str) -> datetime:
    t = datetime.fromisoformat(s.strip().replace("Z", "+00:00").replace("z", "+00:00"))
    if t.tzinfo is None:
        t = t.replace(tzinfo=timezone.utc)
    return t.astimezone(timezone.utc)


def render_all(data: Data, now: datetime, deny: list[str]) -> dict[str, str]:
    """Every live SVG by relative path. `deny` is applied by privacy.check afterwards;
    no card here renders an activity repo name."""
    plaques = content.active_plaques()
    index = next(i for i, p in enumerate(plaques) if p.id == LIVE_PLAQUE)
    plaque = plaques[index]
    if plaque.repo not in data.live:
        raise RuntimeError("live stars/forks missing for the phishEye plaque")
    stars, forks = data.live[plaque.repo]

    kitsune = KITSUNE.read_bytes() if KITSUNE.exists() else None
    fonts = RuntimeFonts()
    out: dict[str, str] = {}
    for lang in LANGS:
        for layout in LAYOUTS:
            out[f"{lang}/torii-{layout}.svg"] = render_torii_path(data, lang, layout, fonts, kitsune_png=kitsune)
            out[f"{lang}/feed-{layout}.svg"] = render_week(data, now, lang, layout, fonts)
        for kind in STATS:
            out[f"{lang}/stat-{kind}.svg"] = render_stat(kind, data, lang, fonts)
        out[f"{lang}/enso.svg"] = render_enso(data, lang, fonts)
        out[f"{lang}/hours.svg"] = render_hours(data, lang, fonts)
        out[f"{lang}/plaque-{LIVE_PLAQUE}.svg"] = render_plaque(plaque, lang, index, fonts, stars=stars, forks=forks)
    return out


class OutputDirError(RuntimeError):
    """--out exists but is not a directory this generator wrote."""


def _siblings(out: Path, kind: str) -> list[Path]:
    return sorted(out.parent.glob(f".{out.name}.{kind}-*"))


def recover_orphan(out: Path) -> None:
    """A hard kill between the two renames of a swap leaves --out missing and our
    backup beside it. Put it back if it is unambiguous (exactly one, ours)."""
    out = Path(os.path.abspath(out))
    if os.path.lexists(out) or not out.parent.is_dir():
        return
    baks = _siblings(out, "bak")
    if len(baks) == 1 and not baks[0].is_symlink() and (baks[0] / MARKER).is_file():
        os.replace(baks[0], out)


def guard_out(out: Path) -> None:
    """Only ever replace a missing path, an empty dir, or an earlier output (marker)."""
    out = Path(os.path.abspath(out))
    if not os.path.lexists(out):
        return
    if out.is_symlink() or not out.is_dir():
        raise OutputDirError("--out exists and is not a directory; refusing to replace it")
    if next(out.iterdir(), None) is None or (out / MARKER).is_file():
        return
    raise OutputDirError(
        f"--out is a non-empty directory without the {MARKER} marker; "
        "refusing to replace it (point --out at a dedicated directory)"
    )


def write_atomic(svgs: dict[str, str], out: Path, private: list[str], deny: list[str]) -> None:
    """Write into a temp dir beside `out`, re-check what landed on disk, then swap.

    Crash safety: if anything (incl. KeyboardInterrupt/SIGTERM) interrupts the two
    renames, the old output is put back; a hard kill is repaired by recover_orphan
    on the next run."""
    out = Path(os.path.abspath(out))
    recover_orphan(out)
    guard_out(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=f".{out.name}.tmp-", dir=out.parent))
    backup: Path | None = None
    try:
        for rel, svg in svgs.items():
            p = tmp / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(svg, encoding="utf-8")
        (tmp / MARKER).write_text(MARKER_TEXT, encoding="utf-8")
        on_disk = {str(p.relative_to(tmp)): p.read_text(encoding="utf-8") for p in sorted(tmp.rglob("*.svg"))}
        if set(on_disk) != set(svgs):
            raise RuntimeError("temp dir does not hold exactly the rendered files")
        check(on_disk, private, deny)
        try:
            if os.path.lexists(out):
                backup = Path(tempfile.mkdtemp(prefix=f".{out.name}.bak-", dir=out.parent))
                backup.rmdir()
                os.replace(out, backup)
            os.replace(tmp, out)
        except BaseException:
            if backup is not None and os.path.lexists(backup) and not os.path.lexists(out):
                try:
                    os.replace(backup, out)
                except BaseException:  # never mask the original exception
                    pass
            raise
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    if backup is not None and os.path.lexists(backup):
        if backup.is_dir() and not backup.is_symlink():
            shutil.rmtree(backup, ignore_errors=True)
        else:
            backup.unlink(missing_ok=True)


def _report(e: BaseException, private: list[str], deny: list[str], token: str) -> None:
    """`error: <Type>: <scrubbed message>`; just the type if scrubbing itself fails."""
    name = type(e).__name__
    try:
        msg = scrub(str(e), private, deny)
        if token:
            msg = msg.replace(token, "***")
    except BaseException:  # noqa: BLE001 - an unscrubbed message must never print
        print(f"error: {name}", file=sys.stderr)
        return
    print(f"error: {name}: {msg}", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m scripts.generate")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--fixtures", type=Path)
    ap.add_argument("--now", type=parse_now, help="override 'now', e.g. 2026-11-12T00:00Z")
    args = ap.parse_args(argv)

    deny = parse_denylist(os.environ.get("PROFILE_DENYLIST"))
    short = sum(1 for t in deny if len(t) < 3)
    if short:
        noun = "term" if short == 1 else "terms"
        print(f"warning: {short} deny-list {noun} shorter than 3 characters", file=sys.stderr)
    token = (os.environ.get("PROFILE_TOKEN") or "").strip()
    if not args.fixtures and not token:
        print("error: PROFILE_TOKEN is not set (or pass --fixtures DIR)", file=sys.stderr)
        return 2

    private: list[str] = []
    try:
        recover_orphan(args.out)
        guard_out(args.out)
        if args.fixtures:
            data = load_fixture(args.fixtures)
        else:
            data = fetch(token, login=LOGIN, now=args.now)
        private = list(data.private_repo_names)
        now = args.now or datetime.now(timezone.utc)
        svgs = render_all(data, now, deny)
        check(svgs, private, deny)
        write_atomic(svgs, args.out, private, deny)
    except Exception as e:  # noqa: BLE001 - every failure must stop the publish
        _report(e, private, deny, token)
        return 1
    except BaseException as e:  # KeyboardInterrupt / SystemExit mid-run: type only
        print(f"error: {type(e).__name__}", file=sys.stderr)
        return 1
    print(f"generated {len(svgs)} files")
    return 0


def entry() -> None:
    """Module entry point. Never lets Python print a traceback: a chained traceback
    could carry an unscrubbed exception message."""
    try:
        code = main()
    except SystemExit:
        raise
    except BaseException as e:  # noqa: BLE001
        try:
            sys.stderr.write(f"error: {type(e).__name__}\n")
            sys.stderr.flush()
            sys.stdout.flush()
        finally:
            os._exit(1)
    sys.exit(code)


if __name__ == "__main__":
    entry()
